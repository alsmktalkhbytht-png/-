    im = Image.open(src).convert("RGB")
    w, h = im.size
    im = im.resize((int(w * 1.5), int(h * 1.5)), Image.LANCZOS).filter(
        ImageFilter.UnsharpMask(radius=1.4, percent=70, threshold=2))
    im.save(os.path.join(REPO, folder, "poem.jpg"), quality=92)
    f = os.path.join(REPO, folder, "lecture.json")
    d = json.load(open(f))
    d["questions"]["ending"] = {"image": "poem.jpg", "label_ar": "أشعار", "poem": poem}
